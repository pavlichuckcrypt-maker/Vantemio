import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { Contract, JsonRpcProvider } from 'ethers';
import { ROOT, compile } from '../src/compile.mjs';
import { DEMO_HOME } from '../src/vault.mjs';
import { verifyAudit } from '../src/security.mjs';
const before=JSON.parse(fs.readFileSync(path.join(ROOT,'runtime/pre-restart-public.json'),'utf8'));
const after=await (await fetch('http://127.0.0.1:18337/api/evidence')).json();
assert.deepEqual(after.manifest,before.manifest);
assert.deepEqual(after.releases,before.releases);
assert.deepEqual(after.orders,before.orders);
assert.deepEqual(after.commerce,before.commerce);
assert.equal(after.paused,false);assert.equal(verifyAudit(),true);
const provider=new JsonRpcProvider('http://127.0.0.1:19545',31337,{staticNetwork:true});
const nft=new Contract(after.manifest.nft,compile().StudioRelease.abi,provider);
assert.equal(await nft.ownerOf('1'),after.releases[0].owner);
assert.equal((await nft.nextTokenId()).toString(),'2');provider.destroy();
const file=path.join(ROOT,'evidence/DEMO_VERIFICATION.json');
const report=JSON.parse(fs.readFileSync(file,'utf8'));
report.tests=report.tests.filter(t=>t.name!=='restart preserves NFT ownership, orders, refunds and balances');
report.tests.push({name:'restart preserves NFT ownership, orders, refunds and balances',passed:true});
report.testsPassed=report.tests.length;report.evidence=after;
report.recoveryVerifiedAt=new Date().toISOString();
const text=JSON.stringify(report,null,2)+'\n';
fs.writeFileSync(file,text);fs.writeFileSync(path.join(DEMO_HOME,'DEMO_VERIFICATION.json'),text,{mode:0o600});
console.log('PASS restart recovery; '+report.testsPassed+' live scenarios recorded.');
